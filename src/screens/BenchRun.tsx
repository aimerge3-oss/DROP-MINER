import { useEffect, useRef, useState } from 'react';
import { useGame, uidMapOf } from '../state/gameStore';
import { BENCHMARKS, BENCH_MAP } from '../data/benchmarks';
import { resolveBuild, buildReadiness } from '../engine/compatibility';
import { runBenchmark, predict } from '../engine/benchmark';
import { mulberry32, hashSeed } from '../engine/rng';
import { Panel, StatRow, Bar, EmptyState, fmt } from '../ui/components';
import type { BenchmarkRun } from '../types';

type Phase = 'select' | 'running' | 'result';

export default function BenchRun() {
  const g = useGame();
  const [phase, setPhase] = useState<Phase>('select');
  const [benchId, setBenchId] = useState<string>(BENCHMARKS[0].id);
  const [progress, setProgress] = useState(0);
  const [fpsNow, setFpsNow] = useState(0);
  const [graph, setGraph] = useState<number[]>([]);
  const [result, setResult] = useState<BenchmarkRun | null>(null);

  const build = g.builds.find((b) => b.id === g.activeBuildId) ?? null;
  const uidMap = uidMapOf(g.inventory);
  const rb = build ? resolveBuild(build, uidMap) : null;
  const ready = rb ? buildReadiness(rb).ready : false;
  const bench = BENCH_MAP.get(benchId)!;
  const pred = build && ready ? predict(build, bench, uidMap) : null;
  const prevBest = g.runs.filter((r) => r.benchId === benchId).reduce((a, r) => Math.max(a, r.score), 0);

  const rafRef = useRef(0);
  useEffect(() => {
    if (phase !== 'running' || !build) return;
    const dur = (g.settings.fastBenchmark ? 2500 : bench.durationMs);
    const target = pred && pred.ready ? pred.avgFpsEst : 30;
    const rng = mulberry32(hashSeed(`${benchId}|${build.id}|live`));
    const t0 = performance.now();
    let acc: number[] = [];
    const tick = (now: number) => {
      const p = Math.min(1, (now - t0) / dur);
      setProgress(p);
      // instantaneous fps wobble around target, dips based on stability prediction
      const instab = pred && !pred.stable ? 0.35 : pred?.throttled ? 0.2 : 0.08;
      const v = Math.max(1, Math.round(target * (1 + (rng() - 0.5) * instab * 2)));
      setFpsNow(v);
      acc = [...acc.slice(-60), v];
      setGraph(acc);
      if (p < 1) rafRef.current = requestAnimationFrame(tick);
      else {
        try {
          const { run } = runBenchmark(build, bench, uidMap, prevBest);
          g.recordRun(run);
          setResult(run);
          setPhase('result');
        } catch (e) {
          g.notify(e instanceof Error ? e.message : 'Benchmark failed to start.', 'error');
          setPhase('select');
        }
      }
    };
    rafRef.current = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(rafRef.current);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [phase]);

  if (phase === 'running') {
    return (
      <>
        <div className="screen-title">{bench.icon} {bench.name}</div>
        <div className="screen-sub"><span className="pulse-dot" /> Running simulated workload… <span className="mono">{Math.round(progress * 100)}%</span></div>
        <Panel>
          <div className="row" style={{ justifyContent: 'space-between', marginBottom: 8 }}>
            <b className="mono" style={{ fontSize: 30, color: 'var(--lime)' }}>{fpsNow} <span style={{ fontSize: 13 }} className="muted">sim fps</span></b>
            <span className="tiny muted mono">{build?.name}</span>
          </div>
          <svg className="fps-graph" viewBox="0 0 300 100" preserveAspectRatio="none">
            <polyline fill="none" stroke="url(#g)" strokeWidth="2"
              points={graph.map((v, i) => `${(i / Math.max(1, graph.length - 1)) * 300},${100 - Math.min(100, (v / Math.max(10, pred?.avgFpsEst ?? 60)) * 88)}`).join(' ')} />
            <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stopColor="#6fd2ff" /><stop offset="1" stopColor="#a3ff3d" /></linearGradient></defs>
          </svg>
          <div style={{ marginTop: 12 }}><Bar pct={progress * 100} /></div>
          <p className="tiny muted" style={{ marginTop: 10 }}>Simulated frames generated by the DROP MINER model — this does not measure your real PC.</p>
        </Panel>
      </>
    );
  }

  if (phase === 'result' && result) {
    const best = g.stats.bestScore;
    const improved = result.score > prevBest && prevBest > 0;
    return (
      <>
        <div className="screen-title">Benchmark Results</div>
        <div className="screen-sub">{BENCH_MAP.get(result.benchId)?.icon} {BENCH_MAP.get(result.benchId)?.name} · {result.buildName}</div>
        <div className="grid cols-2">
          <Panel style={{ textAlign: 'center' }}>
            <div style={{ fontSize: 54, fontWeight: 900, color: result.failed ? '#ff9b9b' : result.stable ? 'var(--lime)' : 'var(--gold)' }}>
              {result.failed ? '💥 CRASH' : fmt(result.score)}
            </div>
            <div className="muted tiny">score {improved && '· 🏆 new personal record!'}</div>
            <div className="row" style={{ justifyContent: 'center', marginTop: 14 }}>
              <button className="btn primary" onClick={() => { setPhase('select'); setResult(null); }}>Done</button>
              <button className="btn ice" onClick={() => { setResult(null); setPhase('running'); }}>Run again</button>
            </div>
          </Panel>
          <Panel>
            <StatRow label="Average FPS" value={result.avgFps} />
            <StatRow label="1% low FPS" value={result.low1Fps} />
            <StatRow label="Max temperature" value={`${result.maxTempC}°C${result.throttled ? ' (throttled)' : ''}`} />
            <StatRow label="System power draw" value={`${fmt(result.powerW)} W`} />
            <StatRow label="Stability" value={result.failed ? 'Failed (PSU overload)' : result.stable ? 'Stable ✅' : 'Unstable ⚠'} />
            <StatRow label="Credits earned" value={<span style={{ color: 'var(--gold)' }}>+{fmt(result.creditsEarned)} cr</span>} />
            <StatRow label="Previous best" value={prevBest ? fmt(prevBest) : 'first run'} />
            <StatRow label="All-time best score" value={fmt(best)} />
          </Panel>
        </div>
        <HistoryPanel benchId={null} />
      </>
    );
  }

  // ── select phase ──
  return (
    <>
      <div className="screen-title">FPS Benchmarks</div>
      <div className="screen-sub">Choose a simulated workload for <b>{build?.name ?? 'no build'}</b>.</div>
      {!build && <EmptyState icon="🖥️" title="No build selected" sub="Create and complete a build in the PC Builder first." />}
      <div className="grid cols-2">
        {BENCHMARKS.map((b) => {
          const locked = g.stats.bestScore < b.unlockScore;
          const vramOk = (rb?.gpu?.vramGB ?? 0) >= b.minVRAM;
          const p = build && ready && !locked ? predict(build, b, uidMap) : null;
          return (
            <Panel key={b.id} style={{ borderColor: `${b.accent}44` }}>
              <div data-lock={locked ? `🏆 Reach ${fmt(b.unlockScore)} score to unlock` : undefined} className={locked ? 'locked-state' : ''} style={{ borderRadius: 16, padding: 2 }}>
                <div className="row"><span style={{ fontSize: 30 }}>{b.icon}</span>
                  <div><b>{b.name}</b><div className="tiny muted">Difficulty {'★'.repeat(b.difficulty)} · needs {b.minVRAM} GB VRAM · reward base {b.rewardBase} cr</div></div>
                </div>
                <p className="tiny muted" style={{ margin: '8px 0' }}>{b.blurb}</p>
                {p?.ready && (
                  <div className="row tiny mono" style={{ gap: 14 }}>
                    <span>≈{p.avgFpsEst} fps</span><span>≈{fmt(p.scoreEst)} pts</span>
                    <span style={{ color: p.tempEst >= 85 ? '#ff9b9b' : 'var(--ice)' }}>{p.tempEst}°C</span>
                    <span style={{ color: p.stable ? 'var(--lime)' : 'var(--gold)' }}>{p.stable ? 'stable' : 'unstable'}</span>
                    {!vramOk && <span style={{ color: '#ff9b9b' }}>⚠ low VRAM</span>}
                  </div>
                )}
                <div className="row" style={{ marginTop: 12 }}>
                  <button className="btn primary" disabled={!ready || locked}
                    onClick={() => { setBenchId(b.id); setProgress(0); setGraph([]); setPhase('running'); }}>
                    ▶ Run benchmark
                  </button>
                  {!ready && !locked && <span className="tiny muted">Install all components first.</span>}
                </div>
              </div>
            </Panel>
          );
        })}
      </div>
      <HistoryPanel benchId={benchId} />
    </>
  );
}

function HistoryPanel({ benchId }: { benchId: string | null }) {
  const g = useGame();
  const runs = g.runs.filter((r) => !benchId || r.benchId === benchId).slice(0, 8);
  if (runs.length === 0) return null;
  return (
    <Panel className="section-gap">
      <h3 style={{ fontSize: 15, marginBottom: 10 }}>🕘 Recent history</h3>
      {runs.map((r) => (
        <div key={r.id} className="stat-row">
          <span className="tiny muted mono">{new Date(r.timestamp).toLocaleString()}</span>
          <span className="tiny">{BENCH_MAP.get(r.benchId)?.icon} {r.buildName} · {r.hardwareSummary}</span>
          <b>{fmt(r.score)} pts · {r.avgFps} fps {r.failed ? '💥' : r.stable ? '✅' : '⚠'} · +{r.creditsEarned} cr</b>
        </div>
      ))}
    </Panel>
  );
}
